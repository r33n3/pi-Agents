import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "packages/coding-agent/src/core/serve/browser/app.ts");
const output = path.join(root, "packages/coding-agent/src/core/serve/browser-bundle.generated.ts");
const result = await build({
	entryPoints: [entry],
	bundle: true,
	format: "iife",
	platform: "browser",
	target: "es2022",
	write: false,
	minify: true,
	sourcemap: false,
});
const bundle = result.outputFiles[0].text;
const generated = `// Generated by scripts/generate-serve-browser.mjs. Do not edit.\n// biome-ignore lint/suspicious/noTemplateCurlyInString: bundled third-party source is an opaque string\nexport const SERVE_BROWSER_BUNDLE = ${JSON.stringify(bundle)};\n`;

if (process.argv.includes("--check")) {
	const current = await readFile(output, "utf8").catch(() => "");
	if (current !== generated) {
		console.error("Serve browser bundle is stale. Run: node scripts/generate-serve-browser.mjs");
		process.exitCode = 1;
	}
} else {
	await writeFile(output, generated);
}
